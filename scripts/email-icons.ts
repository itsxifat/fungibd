const TONES = { g: "#02604A", w: "#FFFFFF", m: "#9AA39E" } as const;
const SIZE = 96; // rendered at 4× of the 24px grid → sharp at every display size used in emails (≤ 48px @2x)

async function main() {
  const out = path.resolve(process.cwd(), "public/email/icons");
  await mkdir(out, { recursive: true });
  for (const [name, shapes] of Object.entries(ICONS)) {
    for (const [tone, color] of Object.entries(TONES)) {
      const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${shapes}</svg>`;
      await sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toFile(path.join(out, `${name}-${tone}.png`));
    }
  }
  console.log(`Wrote ${Object.keys(ICONS).length * Object.keys(TONES).length} icons to ${out}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
